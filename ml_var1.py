def ridge_regression(X, y, lam):
    n_features = X.shape[1]

    I = np.eye(n_features)
    I[0, 0] = 0

    A = X.T @ X + lam * I
    b = X.T @ y

    beta = np.linalg.solve(A, b)

    return beta

