def polynomial_features(X, degree):
    X_poly = []

    # Bias term
    X_poly.append(np.ones((X.shape[0], 1)))

    for d in range(1, degree + 1):
        X_poly.append(X ** d)

    return np.concatenate(X_poly, axis=1)

def polynomial_features_interaction(X, degree):
    n_samples, n_features = X.shape
    X_poly = []

    # Bias / intercept term
    X_poly.append(np.ones(n_samples))

    # Generate all exponent combinations
    def generate_exponents(pos, remaining, exponents):
        if pos == n_features - 1:
            exponents.append(remaining)
            yield exponents
            exponents.pop()
            return

        for power in range(remaining + 1):
            exponents.append(power)

            yield from generate_exponents(
                pos + 1,
                remaining - power,
                exponents
            )

            exponents.pop()

    # Generate terms of each total degree
    for d in range(1, degree + 1):
        for powers in generate_exponents(0, d, []):
            term = np.ones(n_samples)

            for j in range(n_features):
                if powers[j] > 0:
                    term *= X[:, j] ** powers[j]

            X_poly.append(term)

    return np.array(X_poly).T

def fit_linear_regression(X, y):
    beta = np.linalg.lstsq(X, y, rcond=None)[0]

    return beta

def predict(X, beta):
    return X @ beta

def mse(y_true, y_pred):
    return np.mean((y_true - y_pred) ** 2)

def r2_score(y_true, y_pred):
    ss_res = np.sum((y_true - y_pred) ** 2)
    ss_tot = np.sum((y_true - np.mean(y_true)) ** 2)

    return 1 - (ss_res / ss_tot)

